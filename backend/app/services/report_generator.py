"""
ReportLab PDF Generation Service for ResumeAI Analysis Reports.
Creates an executive-level, multi-page professional PDF report.
"""

import io
from typing import Dict, Any, List

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
    HRFlowable,
)
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and print 'Page X of Y'
    along with running headers and footers.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(40, 755, "ResumeAI — AI-Powered Resume Analysis & Career Roadmap")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(40, 747, 572, 747)

        # Running footer on every page
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(40, 36, 572, 36)

        self.drawString(40, 24, "Confidential — Generated by ResumeAI Platform")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(572, 24, page_text)
        self.restoreState()


def get_category_color(score: int) -> colors.Color:
    if score >= 85:
        return colors.HexColor("#059669")  # Green
    elif score >= 70:
        return colors.HexColor("#2563EB")  # Blue
    elif score >= 50:
        return colors.HexColor("#D97706")  # Amber
    else:
        return colors.HexColor("#DC2626")  # Red


def generate_pdf_report(analysis_data: Dict[str, Any]) -> io.BytesIO:
    """
    Compiles analysis JSON into a high-quality multi-page PDF document.
    Returns in-memory BytesIO buffer.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=40,
        rightMargin=40,
        topMargin=46,
        bottomMargin=46,
    )

    styles = getSampleStyleSheet()

    # Custom typography
    navy = colors.HexColor("#0F172A")
    indigo = colors.HexColor("#4F46E5")
    slate = colors.HexColor("#334155")
    light_slate = colors.HexColor("#64748B")
    card_bg = colors.HexColor("#F8FAFC")
    border_color = colors.HexColor("#E2E8F0")

    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=navy,
        spaceAfter=4,
    )

    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=light_slate,
    )

    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=indigo,
        spaceBefore=12,
        spaceAfter=6,
    )

    body_style = ParagraphStyle(
        "CustomBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=slate,
    )

    bold_body = ParagraphStyle(
        "BoldBody",
        parent=body_style,
        fontName="Helvetica-Bold",
        textColor=navy,
    )

    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Italic"],
        fontName="Helvetica-Oblique",
        fontSize=7.5,
        leading=10.5,
        textColor=light_slate,
    )

    story = []

    # 1. Header Banner
    candidate_name = analysis_data.get("candidate_name") or "Candidate"
    filename = analysis_data.get("filename") or "Resume.pdf"
    role = analysis_data.get("selected_role") or "Software Developer"
    created_at = analysis_data.get("created_at") or "Today"

    header_table_data = [
        [
            Paragraph("<b>ResumeAI Evaluation Report</b>", title_style),
            Paragraph(f"<b>Date:</b> {created_at}<br/><b>Target Role:</b> {role}", subtitle_style),
        ],
        [
            Paragraph(f"Candidate: <b>{candidate_name}</b> &nbsp;|&nbsp; File: <b>{filename}</b>", subtitle_style),
            Paragraph("Generated via Gemini AI Engine", subtitle_style),
        ]
    ]
    header_table = Table(header_table_data, colWidths=[332, 200])
    header_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=1.5, color=indigo, spaceBefore=0, spaceAfter=10))

    # 2. Executive Summary & Match Score
    match_score = analysis_data.get("match_score", {})
    overall_score = match_score.get("overall_score", 0)
    category = match_score.get("match_category", "Evaluation")
    explanation = match_score.get("explanation", "")
    breakdown = match_score.get("score_breakdown", {})
    disclaimer = match_score.get("disclaimer", "")

    score_color = get_category_color(overall_score)

    score_box_content = [
        [
            Paragraph(f"<font color='{score_color.hexval()}'><b>{overall_score}</b>/100</font>", ParagraphStyle(
                "BigScore", fontName="Helvetica-Bold", fontSize=26, leading=30, alignment=1
            )),
            Paragraph(
                f"<b>AI Job Match Estimate: <font color='{score_color.hexval()}'>{category}</font></b><br/><br/>"
                f"{explanation}",
                body_style
            )
        ]
    ]
    score_table = Table(score_box_content, colWidths=[120, 412])
    score_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), card_bg),
        ("BOX", (0, 0), (-1, -1), 1, border_color),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(score_table)
    story.append(Spacer(1, 6))

    # Score breakdown bar table
    breakdown_data = [
        [
            Paragraph("<b>Factor</b>", bold_body),
            Paragraph("<b>Skills Alignment</b>", bold_body),
            Paragraph("<b>Keywords Coverage</b>", bold_body),
            Paragraph("<b>Projects & Experience</b>", bold_body),
            Paragraph("<b>Education & Role Fit</b>", bold_body),
        ],
        [
            Paragraph("Score", body_style),
            Paragraph(f"<b>{breakdown.get('skills_score', 0)}%</b>", body_style),
            Paragraph(f"<b>{breakdown.get('keywords_score', 0)}%</b>", body_style),
            Paragraph(f"<b>{breakdown.get('experience_score', 0)}%</b>", body_style),
            Paragraph(f"<b>{breakdown.get('education_score', 0)}%</b>", body_style),
        ]
    ]
    breakdown_table = Table(breakdown_data, colWidths=[100, 108, 108, 108, 108])
    breakdown_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F6")),
        ("GRID", (0, 0), (-1, -1), 0.5, border_color),
        ("ALIGN", (1, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("PADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(breakdown_table)

    if disclaimer:
        story.append(Spacer(1, 4))
        story.append(Paragraph(f"<b>Notice:</b> {disclaimer}", disclaimer_style))

    story.append(Spacer(1, 10))

    # 3. Skills Analysis & Keyword Alignment
    story.append(Paragraph("1. Skills & Keyword Comparative Analysis", section_heading))

    skills_data = analysis_data.get("skills_analysis", {})
    matching = skills_data.get("matching_skills", [])
    missing = skills_data.get("missing_skills", [])
    additional = skills_data.get("additional_skills", [])

    keywords_data = analysis_data.get("keyword_analysis", {})
    found_kw = keywords_data.get("found_keywords", [])
    missing_kw = keywords_data.get("missing_keywords", [])

    skills_summary_data = [
        [
            Paragraph("<b>Category</b>", bold_body),
            Paragraph("<b>Identified Technical Elements</b>", bold_body)
        ],
        [
            Paragraph("<font color='#059669'><b>Matching Skills</b></font>", bold_body),
            Paragraph(", ".join(matching) if matching else "None identified", body_style)
        ],
        [
            Paragraph("<font color='#DC2626'><b>Missing Skills (JD)</b></font>", bold_body),
            Paragraph(", ".join(missing) if missing else "None identified — great match!", body_style)
        ],
        [
            Paragraph("<font color='#4F46E5'><b>Additional Candidate Skills</b></font>", bold_body),
            Paragraph(", ".join(additional) if additional else "None noted", body_style)
        ],
        [
            Paragraph("<b>Found Keywords</b>", bold_body),
            Paragraph(", ".join(found_kw) if found_kw else "None", body_style)
        ],
        [
            Paragraph("<font color='#D97706'><b>Missing Keywords</b></font>", bold_body),
            Paragraph(", ".join(missing_kw) if missing_kw else "None", body_style)
        ],
    ]
    skills_table = Table(skills_summary_data, colWidths=[140, 392])
    skills_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F6")),
        ("GRID", (0, 0), (-1, -1), 0.5, border_color),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("PADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(skills_table)
    story.append(Spacer(1, 10))

    # 4. Resume Strengths & Improvement Areas
    story.append(Paragraph("2. Strengths & High-Impact Improvement Areas", section_heading))

    strengths = analysis_data.get("strengths", {})
    improvements = analysis_data.get("improvement_areas", {})

    strong_sections = strengths.get("strong_sections", [])
    relevant_projects = strengths.get("relevant_projects", [])
    weak_bullets = improvements.get("weak_bullet_points", [])
    missing_info = improvements.get("missing_information", [])

    def format_bullets(items: List[str]) -> str:
        if not items:
            return "No specific items noted."
        return "<br/>".join([f"• {item}" for item in items])

    eval_data = [
        [
            Paragraph("<b>Resume Strengths</b>", bold_body),
            Paragraph("<b>Areas for Enhancement</b>", bold_body)
        ],
        [
            Paragraph(f"<b>Key Highlights:</b><br/>{format_bullets(strong_sections)}<br/><br/><b>Projects:</b><br/>{format_bullets(relevant_projects)}", body_style),
            Paragraph(f"<b>Weak Bullets / Clarity:</b><br/>{format_bullets(weak_bullets)}<br/><br/><b>Missing Context:</b><br/>{format_bullets(missing_info)}", body_style)
        ]
    ]
    eval_table = Table(eval_data, colWidths=[266, 266])
    eval_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F6")),
        ("GRID", (0, 0), (-1, -1), 0.5, border_color),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(eval_table)
    story.append(Spacer(1, 10))

    # 5. Bullet Point Transformations (Before & After)
    bullet_improvements = analysis_data.get("bullet_improvements", [])
    if bullet_improvements:
        story.append(Paragraph("3. AI Resume Bullet Improvements (Before & After)", section_heading))
        story.append(Paragraph("<i>Actionable rewrites using active verbs and impact framing. No metrics are fabricated; replace [X%] with your true results.</i>", disclaimer_style))
        story.append(Spacer(1, 4))

        bullet_table_rows = [
            [
                Paragraph("<b>Original Bullet</b>", bold_body),
                Paragraph("<b>Optimized Professional Version</b>", bold_body),
                Paragraph("<b>Rationale & Action Verbs</b>", bold_body)
            ]
        ]

        for item in bullet_improvements[:5]:
            orig = item.get("original", "")
            improved = item.get("improved", "")
            expl = item.get("explanation", "")
            verbs = ", ".join(item.get("action_verbs_used", []))
            verbs_text = f"<br/><b>Verbs:</b> {verbs}" if verbs else ""

            bullet_table_rows.append([
                Paragraph(orig, body_style),
                Paragraph(f"<b>{improved}</b>", body_style),
                Paragraph(f"{expl}{verbs_text}", body_style)
            ])

        bullet_table = Table(bullet_table_rows, colWidths=[160, 212, 160])
        bullet_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F6")),
            ("GRID", (0, 0), (-1, -1), 0.5, border_color),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("PADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(bullet_table)
        story.append(Spacer(1, 10))

    # 6. Skill-Gap Roadmap & 30-Day Plan
    roadmap = analysis_data.get("skill_gap_roadmap", {})
    high_p = roadmap.get("high_priority", [])
    thirty_day = roadmap.get("thirty_day_plan", [])

    if high_p or thirty_day:
        story.append(Paragraph("4. Targeted Skill-Gap Learning Roadmap", section_heading))

        if high_p:
            high_rows = [
                [
                    Paragraph("<b>High Priority Skill</b>", bold_body),
                    Paragraph("<b>Why It Matters</b>", bold_body),
                    Paragraph("<b>Suggested Proof Project</b>", bold_body)
                ]
            ]
            for h in high_p[:4]:
                high_rows.append([
                    Paragraph(f"<b>{h.get('skill_name', '')}</b><br/>{h.get('what_to_learn', '')}", body_style),
                    Paragraph(h.get("why_it_matters", ""), body_style),
                    Paragraph(h.get("mini_project", ""), body_style),
                ])
            high_table = Table(high_rows, colWidths=[160, 186, 186])
            high_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F6")),
                ("GRID", (0, 0), (-1, -1), 0.5, border_color),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("PADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(high_table)
            story.append(Spacer(1, 6))

        if thirty_day:
            plan_rows = [
                [
                    Paragraph("<b>Timeline</b>", bold_body),
                    Paragraph("<b>Focus Theme</b>", bold_body),
                    Paragraph("<b>Weekly Milestone Deliverable</b>", bold_body)
                ]
            ]
            for w in thirty_day:
                plan_rows.append([
                    Paragraph(f"<b>Week {w.get('week_number', '')}</b>", bold_body),
                    Paragraph(w.get("focus_theme", ""), body_style),
                    Paragraph(w.get("milestone_deliverable", ""), body_style),
                ])
            plan_table = Table(plan_rows, colWidths=[80, 212, 240])
            plan_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F6")),
                ("GRID", (0, 0), (-1, -1), 0.5, border_color),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("PADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(plan_table)
            story.append(Spacer(1, 10))

    # 7. Strategic Recommendations
    recs = analysis_data.get("personalized_recommendations", [])
    if recs:
        story.append(Paragraph("5. Personalized Strategic Next Steps", section_heading))
        rec_items = "<br/>".join([f"<b>{idx+1}.</b> {r}" for idx, r in enumerate(recs)])
        rec_box = Table([[Paragraph(rec_items, body_style)]], colWidths=[532])
        rec_box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), card_bg),
            ("BOX", (0, 0), (-1, -1), 0.5, border_color),
            ("PADDING", (0, 0), (-1, -1), 8),
        ]))
        story.append(rec_box)

    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer
