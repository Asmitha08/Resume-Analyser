    if high_p or thirty_day:
        story.append(Paragraph("2. Targeted Skill-Gap Learning Roadmap (30 Days)", section_heading))

        if high_p:
            high_rows = [
                [
                    Paragraph("<b>High Priority Skill</b>", bold_body),
                    Paragraph("<b>Why It Matters</b>", bold_body),
                    Paragraph("<b>Suggested Proof Project</b>", bold_body)
                ]
            ]
            for h in high_p[:3]:
                high_rows.append([
                    Paragraph(f"<b>{h.get('skill_name', '')}</b><br/>{h.get('what_to_learn', '')}", body_style),
                    Paragraph(h.get("why_it_matters", ""), body_style),
                    Paragraph(h.get("mini_project", ""), body_style),
                ])
            high_table = Table(high_rows, colWidths=[150, 191, 191])
            high_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2F6")),
                ("GRID", (0, 0), (-1, -1), 0.5, border_color),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("PADDING", (0, 0), (-1, -1), 3),
            ]))
            story.append(high_table)
            story.append(Spacer(1, 6))

        if thirty_day:
            plan_rows = [
                [
                    Paragraph("<b>Week</b>", bold_body),
                    Paragraph("<b>Focus Theme</b>", bold_body),
                    Paragraph("<b>Milestone Deliverable</b>", bold_body)
                ]
            ]
            for w in thirty_day[:4]:
                plan_rows.append([
                    Paragraph(f"<b>Week {w.get('week_number', '')}</b>", bold_body),
                    Paragraph(w.get("focus_theme", ""), body_style),
                    Paragraph(w.get("milestone_deliverable", ""), body_style),
                ])
